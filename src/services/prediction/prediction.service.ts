import { MODULES } from "../../config/constants";
import type { ICandleRepository, IPredictionRepository } from "../../database/repositories/interfaces";
import type {
  Candle,
  FeatureVector,
  IndicatorValues,
  PredictionRow,
} from "../../types/domain";
import { toErrorMessage } from "../../utils/errors";
import type { ILogger } from "../../utils/logger";
import type { IFeatureService } from "./feature.service";
import type { IPredictionProvider } from "./prediction.interface";

export interface IPredictionService {
  generate(candle: Candle, indicators: IndicatorValues): Promise<PredictionRow>;
  getLatest(): Promise<PredictionRow | null>;
  getHistory(limit?: number): Promise<PredictionRow[]>;
}

const FEATURE_CANDLE_COUNT = 60;

export class PredictionService implements IPredictionService {
  constructor(
    private readonly candleRepository: ICandleRepository,
    private readonly predictionRepository: IPredictionRepository,
    private readonly featureService: IFeatureService,
    private readonly primaryProvider: IPredictionProvider,
    private readonly fallbackProvider: IPredictionProvider,
    private readonly logger: ILogger,
  ) {}

  async generate(candle: Candle, indicators: IndicatorValues): Promise<PredictionRow> {
    const candles = await this.candleRepository.findRecent(
      candle.symbol,
      candle.interval,
      FEATURE_CANDLE_COUNT,
    );

    const features: FeatureVector = this.featureService.build(candles, indicators);

    let raw;
    try {
      raw = await this.primaryProvider.predict(features);
      this.logger.debug(MODULES.PREDICTION, "Prediction generated by primary provider", {
        provider: this.primaryProvider.name,
        prediction: raw.prediction,
        confidence: raw.confidence,
      });
    } catch (error) {
      this.logger.warn(
        MODULES.PREDICTION,
        `Primary prediction provider failed; using offline fallback (${toErrorMessage(error)})`,
        { provider: this.primaryProvider.name },
      );
      raw = await this.fallbackProvider.predict(features);
    }

    const stored = await this.predictionRepository.create({
      time: new Date(),
      buyProbability: raw.buyProbability,
      sellProbability: raw.sellProbability,
      confidence: raw.confidence,
      prediction: raw.prediction,
    });

    this.logger.info(MODULES.PREDICTION, "Prediction stored", {
      prediction: stored.prediction,
      buyProbability: stored.buyProbability,
      sellProbability: stored.sellProbability,
      confidence: stored.confidence,
      candle: candle.timestamp,
    });

    return stored;
  }

  async getLatest(): Promise<PredictionRow | null> {
    return this.predictionRepository.findLatest();
  }

  async getHistory(limit = 100): Promise<PredictionRow[]> {
    return this.predictionRepository.findMany(limit);
  }
}
